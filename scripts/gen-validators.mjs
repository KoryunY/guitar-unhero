// Precompiles the JSON Schema validators to standalone ESM so the production
// build needs no runtime code generation (no CSP 'unsafe-eval').
// Run: pnpm gen:validators  (a unit test fails if the output is stale).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const score = JSON.parse(readFileSync(join(root, 'Documents/gu-score-v1.schema.json'), 'utf8'));
const manifest = JSON.parse(readFileSync(join(root, 'src/storage/progress-export.schema.json'), 'utf8'));

export function generate() {
  const ajv = new Ajv2020({ allErrors: true, strict: false, validateFormats: true, code: { source: true, esm: true, lines: false } });
  addFormats(ajv);
  ajv.addSchema(score);
  ajv.addSchema(manifest);
  let code = standaloneCode(ajv, { validateScoreSchema: score.$id, validateManifestSchema: manifest.$id });
  // Ajv's ESM output still uses require() for runtime helpers; turn them into imports.
  const imports = [];
  code = code.replace(/require\("([^"]+)"\)\.([A-Za-z_$][\w$]*)/g, (_, mod, prop) => {
    let i = imports.indexOf(mod);
    if (i < 0) i = imports.push(mod) - 1;
    return `__get(__ns${i}, '${prop}')`;
  });
  if (/require\(/.test(code)) throw new Error('Unhandled require() in generated validator');
  // CJS interop differs between bundlers/Node; resolve the export defensively.
  const helper = "function __get(ns, prop) { const m = ns.default ?? ns; if (prop === 'default') return typeof m === 'function' ? m : (m.default ?? ns.default); return ns[prop] ?? m[prop]; }";
  const header = imports.map((m, i) => `import * as __ns${i} from '${m}.js';`).join('\n');
  code = code.replace('"use strict";', '');
  code = `${header}\n${helper}\n${code}`;
  return `// GENERATED by scripts/gen-validators.mjs — do not edit.\n// Sources: Documents/gu-score-v1.schema.json, src/storage/progress-export.schema.json\n/* eslint-disable */\n// @ts-nocheck\n${code}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = join(root, 'src/generated/validators.js');
  writeFileSync(out, generate());
  console.log(`wrote ${out}`);
}
